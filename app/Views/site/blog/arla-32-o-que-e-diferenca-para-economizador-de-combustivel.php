            <p>Quem trabalha com caminhões e máquinas a diesel já ouviu falar do ARLA 32 — mas nem sempre fica claro o que ele realmente faz, e principalmente, qual a diferença dele para um sistema economizador de combustível. São coisas bem diferentes, e entender isso evita confusão na hora de decidir o que seu veículo precisa.</p>

            <h2>O que é o ARLA 32</h2>
            <p>ARLA 32 (Agente Redutor Líquido Automotivo) é uma solução aquosa de ureia, usada em motores diesel modernos equipados com o sistema SCR (Redução Catalítica Seletiva). Ele é injetado no escapamento, antes de sair pelo cano de descarga, e reage quimicamente com os gases do motor para reduzir a emissão de óxidos de nitrogênio (NOx) — um poluente regulado pelas normas de emissão brasileiras (PROCONVE).</p>
            <p>Ou seja: o ARLA 32 não economiza combustível. Ele trata o gás de escape depois que o diesel já foi queimado, para o veículo atender às exigências ambientais.</p>

            <h2>O que é um economizador de combustível</h2>
            <p>Um economizador de combustível, como o <a href="/comprar">Ecodiffusore</a>, atua num momento diferente do processo: antes da queima, otimizando a mistura ar/combustível dentro da câmara de combustão. O resultado é uma queima mais completa do diesel — com menos combustível desperdiçado sem queimar, mais torque disponível, e como consequência, também menos poluentes liberados no escapamento (efeito comprovado em testes de opacidade e NOx, disponíveis na <a href="/comprar#documentacao">documentação técnica</a>).</p>

