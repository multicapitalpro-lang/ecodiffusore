            <p>Quem vive na estrada ou administra uma frota sente isso na pele: o preço do diesel raramente cai, e quando cai, é por pouco tempo. Entender por que isso acontece ajuda a se planejar melhor — e a enxergar por que tecnologia de economia de combustível deixou de ser luxo e virou necessidade operacional.</p>

            <h2>O histórico recente</h2>
            <p>O diesel S10 saiu de uma média de R$ 3,60 em 2019 para valores na casa de R$ 6,00 a R$ 6,70 nos anos seguintes — praticamente dobrando de preço em poucos anos (valores médios nacionais aproximados, referência ANP). Mesmo com oscilações pontuais, a tendência de fundo é clara: o diesel fica mais caro com o tempo.</p>

            <h2>Os principais fatores por trás do preço</h2>
            <h3>1. Preço internacional do petróleo</h3>
            <p>O diesel é derivado do petróleo bruto, cujo preço é definido no mercado internacional (referência Brent). Crises geopolíticas, cortes de produção da OPEP e demanda global afetam diretamente o custo da matéria-prima.</p>

            <h3>2. Câmbio (dólar)</h3>
            <p>O petróleo é cotado em dólar. Quando o real se desvaloriza frente ao dólar, o custo de importação (e da paridade de preço) sobe, mesmo que o petróleo em si não tenha ficado mais caro em dólar.</p>

            <h3>3. Paridade de Preço de Importação (PPI)</h3>
            <p>A política de preços adotada pelas refinarias no Brasil historicamente segue o conceito de paridade internacional: o preço do combustível refinado aqui tende a acompanhar o que custaria importar o produto, mesmo quando é produzido no país.</p>

            <h3>4. Tributos</h3>
            <p>ICMS (estadual), PIS/Cofins e CIDE incidem sobre o diesel, e variam conforme o estado — parte da diferença de preço entre regiões do Brasil vem daí.</p>

            <h3>5. Logística e distribuição</h3>
            <p>Frete até o posto, armazenagem e margem de distribuição também compõem o preço final — e tendem a subir junto com o custo de operação do próprio setor de transporte (inclusive o custo... de diesel, um ciclo que se retroalimenta).</p>

            <h2>O que dá pra fazer diante disso</h2>
            <p>Não dá para controlar o preço do diesel — mas dá para controlar quanto diesel seu veículo ou máquina consome. Duas frentes ajudam:</p>
            <ul>
                <li><strong>Hábitos de uso</strong>: direção econômica, manutenção em dia, calibragem de pneus (veja nosso <a href="/blog/como-reduzir-consumo-de-diesel-do-caminhao">guia de 7 dicas para reduzir consumo</a>).</li>
                <li><strong>Tecnologia de otimização de combustão</strong>: sistemas como o <a href="/comprar">Ecodiffusore</a>, que reduzem de 5% a 20% o consumo de diesel independente do preço do combustível — quanto mais caro o diesel fica, maior o valor absoluto que essa economia representa no fim do mês.</li>
            </ul>
            <p>Faz sentido: se o diesel só tende a subir, a economia percentual de hoje vale cada vez mais em reais amanhã.</p>

