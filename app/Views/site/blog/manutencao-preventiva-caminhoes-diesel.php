            <p>Boa parte do consumo excessivo de diesel não vem de defeito grave — vem de pequenas negligências de manutenção que se acumulam sem ninguém perceber. Este guia lista os itens que mais impactam o consumo, e com que frequência vale a pena checar cada um.</p>

            <h2>Filtro de ar</h2>
            <p>Um filtro de ar sujo restringe a entrada de ar no motor, prejudicando a mistura ar/combustível e forçando o motor a compensar queimando mais diesel pra manter a potência. Verifique a cada troca de óleo, e troque antes se estiver visivelmente sujo.</p>

            <h2>Sistema de injeção</h2>
            <p>Bicos injetores desregulados ou sujos alteram o padrão de pulverização do diesel na câmara de combustão, prejudicando a queima. Manutenção periódica no sistema de injeção, conforme o manual do fabricante, evita perda de eficiência silenciosa.</p>

            <h2>Óleo do motor</h2>
            <p>Óleo vencido ou fora de especificação aumenta o atrito interno do motor, que precisa de mais energia (e mais diesel) pra funcionar. Respeitar o intervalo de troca recomendado pelo fabricante é básico, mas segue sendo um dos itens mais negligenciados.</p>

            <h2>Calibragem dos pneus</h2>
            <p>Pneu murcho aumenta o atrito com o asfalto — o motor precisa trabalhar mais pra manter a mesma velocidade. Confira a calibragem semanalmente, sempre com o pneu frio (antes de rodar).</p>

            <h2>Sistema de arrefecimento</h2>
            <p>Motor rodando fora da temperatura ideal (muito frio ou superaquecendo) perde eficiência de combustão. Manter o sistema de arrefecimento em dia (nível de fluido, radiador limpo) evita esse tipo de perda.</p>

            <h2>Alinhamento e suspensão</h2>
            <p>Alinhamento incorreto aumenta o atrito dos pneus com o solo de forma sutil, mas constante — o efeito no consumo aparece ao longo de milhares de quilômetros.</p>

            <h2>Um investimento único que não compete com a manutenção</h2>
            <p>Diferente dos itens acima, que exigem atenção recorrente, o <a href="/comprar">Ecodiffusore</a> é uma peça mecânica de instalação única, sem manutenção — ele continua entregando economia mesmo nos períodos entre uma revisão e outra, sem adicionar mais um item à sua rotina de manutenção.</p>

