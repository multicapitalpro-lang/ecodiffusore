            <p>Chegar no posto e ver duas opções de diesel — S10 e S500 — gera dúvida em muita gente: qual usar, e será que isso afeta o consumo? A diferença é real, e entender ela ajuda a tomar a decisão certa pro seu motor.</p>

            <h2>O que significa "S10" e "S500"</h2>
            <p>O número se refere à quantidade de enxofre presente no combustível, medida em partes por milhão (ppm):</p>
            <ul>
                <li><strong>Diesel S10</strong>: até 10 ppm de enxofre — o mais puro, disponível nacionalmente.</li>
                <li><strong>Diesel S500</strong>: até 500 ppm de enxofre — bem mais enxofre que o S10.</li>
            </ul>
            <p>Menos enxofre significa combustão mais limpa e menos desgaste em componentes sensíveis do motor, como o sistema de injeção eletrônica e o filtro de particulados.</p>

            <h2>Qual seu motor precisa</h2>
            <p>Motores diesel modernos, especialmente os equipados com sistema SCR (que usa ARLA 32) e filtro de particulados, são projetados para rodar com S10 — usar S500 nesses motores pode comprometer componentes caros e até anular garantia de fábrica. Motores mais antigos, sem essa tecnologia, costumam tolerar os dois, mas o fabricante do veículo é sempre a referência final.</p>

            <h2>Isso afeta o consumo?</h2>
            <p>A diferença de rendimento entre S10 e S500 tende a ser pequena isoladamente, mas o S10 favorece uma combustão mais eficiente e reduz o acúmulo de resíduos no motor ao longo do tempo — o que, indiretamente, ajuda a manter o consumo estável e evita perda de rendimento por sujeira acumulada em bicos injetores e filtros.</p>

            <h2>Combinando diesel de qualidade com tecnologia de economia</h2>
            <p>Usar o combustível certo pro seu motor é uma das <a href="/blog/como-reduzir-consumo-de-diesel-do-caminhao">7 práticas que ajudam a reduzir consumo de diesel</a> — mas o ganho mais expressivo vem de combinar isso com tecnologia de otimização de combustão. O <a href="/comprar">Ecodiffusore</a> melhora a mistura ar/combustível independente do tipo de diesel usado, entregando de 5% a 20% de economia adicional sobre o que já é economizado com bons hábitos de manutenção e abastecimento.</p>

